/**
 * What to do about a Check Control message: how urgent it is, what it means, the first steps.
 * Keyed by the Russian title from [CheckControl.translate], because every spelling of one message
 * already converges on one title there. Pure data; the texts are for this car (X5 E53).
 */
object CheckControlGuide {
    enum class Severity {
        /** Stop the engine as soon as it is safe. Opens full screen by itself. */
        STOP,
        /** Drive on carefully, get it seen to soon. */
        SERVICE,
        /** Nothing urgent. */
        INFO,
    }

    data class Guide(
        val severity: Severity,
        val meaning: String,
        val steps: List<String>,
        /** Lamps this message is about, to pick the LCM's live fault bits that belong to it. */
        val lamps: Set<Lamp> = emptySet(),
        /** First step only when the light module did not say which bulb: find it by eye. */
        val findFirst: String? = null,
    ) {
        fun stepsFor(faultyLamps: List<String>): List<String> =
            if (faultyLamps.isEmpty() && findFirst != null) listOf(findFirst) + steps else steps
    }

    internal fun forTitle(title: String): Guide? =
        GUIDES[title] ?: if (title.startsWith("Ограничение скорости")) LIMIT else null

    fun forText(clusterText: String): Guide? = forTitle(CheckControl.translate(clusterText))

    /** Russian names of the dead bulbs that belong to this message, from the LCM's live report. */
    fun faultyLampsFor(clusterText: String, faults: Set<Lamp>): List<String> {
        return faultyLampSetFor(clusterText, faults).map { it.ru }
    }

    /**
     * Brake and tail bulb dead on the SAME side sit in one rear lamp: two bulbs rarely die together,
     * so the common holder or connector is the likelier culprit. Seen on this car on 2026-10-15.
     */
    fun hint(faults: Collection<Lamp>): String? = when {
        Lamp.BRAKE_LEFT in faults && Lamp.REAR_LEFT in faults -> SAME_LAMP_HINT
        Lamp.BRAKE_RIGHT in faults && Lamp.REAR_RIGHT in faults -> SAME_LAMP_HINT
        else -> null
    }

    private const val SAME_LAMP_HINT =
        "Обе лампы в одном фонаре. Сразу две перегорают редко, начните с разъёма и контактов платы."

    /** [faultyLampsFor] keeps names only; this keeps the lamps, for [hint]. */
    fun faultyLampSetFor(clusterText: String, faults: Set<Lamp>): Set<Lamp> {
        val mine = forText(clusterText)?.lamps ?: return emptySet()
        return faults.filterTo(LinkedHashSet()) { it in mine }
    }

    fun severity(clusterText: String): Severity = forText(clusterText)?.severity ?: Severity.INFO

